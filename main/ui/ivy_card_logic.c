const uint16_t *ivy_glyph12_find(uint32_t codepoint) {
    size_t lo = 0;
    size_t hi = sizeof(s_glyphs12) / sizeof(s_glyphs12[0]);
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        if (s_glyphs12[mid].cp == codepoint) {
            return s_glyphs12[mid].rows;
        }
        if (s_glyphs12[mid].cp < codepoint) {
            lo = mid + 1u;
        } else {
            hi = mid;
        }
    }
    return NULL;
}

static uint32_t next_rand(ivy_card_state_t *st) {
    uint32_t x = st->rng_state ? st->rng_state : 0x20261115u;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    st->rng_state = x;
    return x;
}

static int16_t rand_range(ivy_card_state_t *st, int16_t lo, int16_t hi) {
    uint32_t span = (uint32_t)(hi - lo + 1);
    return (int16_t)(lo + (int16_t)(next_rand(st) % span));
}

static void spawn_particle(ivy_card_state_t *st, ivy_particle_kind_t kind,
                           int16_t x, int16_t y, int16_t vx_q4, int16_t vy_q4,
                           uint16_t color565, uint8_t ttl) {
    int slot = -1;
    uint8_t min_ttl = 255;
    int oldest_slot = 0;
    for (int i = 0; i < IVY_PARTICLE_MAX; ++i) {
        if (st->particles[i].kind == IVY_PARTICLE_NONE || st->particles[i].ttl == 0) {
            slot = i;
            break;
        }
        if (st->particles[i].ttl < min_ttl) {
            min_ttl = st->particles[i].ttl;
            oldest_slot = i;
        }
    }
    if (slot < 0) {
        slot = oldest_slot;
    }
    st->particles[slot] = (ivy_particle_t){
        .x_q4 = (int16_t)(x << 4),
        .y_q4 = (int16_t)(y << 4),
        .vx_q4 = vx_q4,
        .vy_q4 = vy_q4,
        .color565 = color565,
        .ttl = ttl,
        .max_ttl = ttl,
        .kind = kind,
    };
}

static void burst_celebration(ivy_card_state_t *st, int count) {
    static const uint16_t palette[4] = {
        COL565_GOLD, COL565_LIME, COL565_PINK, COL565_CYAN,
    };
    for (int i = 0; i < count; ++i) {
        uint32_t r = next_rand(st);
        ivy_particle_kind_t kind;
        uint32_t m = r % 3u;
        if (m == 0u) {
            kind = IVY_PARTICLE_HEART;
        } else if (m == 1u) {
            kind = IVY_PARTICLE_STAR;
        } else {
            kind = IVY_PARTICLE_CONFETTI;
        }
        int16_t x = rand_range(st, 56, 184);
        int16_t y = rand_range(st, 72, 168);
        int16_t vx = rand_range(st, -28, 28);
        int16_t vy = rand_range(st, -34, -8);
        uint16_t col = (kind == IVY_PARTICLE_HEART) ? COL565_PINK : palette[r & 3u];
        uint8_t ttl = (uint8_t)rand_range(st, 18, 34);
        spawn_particle(st, kind, x, y, vx, vy, col, ttl);
    }
}

static void burst_expression(ivy_card_state_t *st, ivy_expr_kind_t expr) {
    for (int i = 0; i < 10; ++i) {
        if (expr == IVY_EXPR_LAUGH) {
            int16_t x = rand_range(st, 42, 198);
            int16_t y = rand_range(st, 58, 168);
            ivy_particle_kind_t k = (i % 2 == 0) ? IVY_PARTICLE_HEART : IVY_PARTICLE_STAR;
            uint16_t col = (k == IVY_PARTICLE_HEART) ? COL565_PINK : COL565_GOLD;
            spawn_particle(st, k, x, y, rand_range(st, -10, 10), rand_range(st, -22, -8), col, 28);
        } else if (expr == IVY_EXPR_SHOCK) {
            int16_t x = rand_range(st, 66, 174);
            int16_t y = rand_range(st, 54, 144);
            ivy_particle_kind_t k = (i % 3 == 0) ? IVY_PARTICLE_HEART : IVY_PARTICLE_CONFETTI;
            uint16_t col = (k == IVY_PARTICLE_HEART) ? COL565_PINK
                         : ((i % 2 == 0) ? COL565_LIME : COL565_GOLD);
            spawn_particle(st, k, x, y, rand_range(st, -32, 32), rand_range(st, -30, -6), col, 24);
        } else if (expr == IVY_EXPR_DEADPAN) {
            int16_t x = rand_range(st, 48, 192);
            int16_t y = rand_range(st, 36, 98);
            ivy_particle_kind_t k = (i % 4 == 0) ? IVY_PARTICLE_HEART : IVY_PARTICLE_SWEAT;
            uint16_t col = (k == IVY_PARTICLE_HEART) ? COL565_PINK : COL565_CYAN;
            spawn_particle(st, k, x, y, rand_range(st, -3, 3),
                           (k == IVY_PARTICLE_HEART) ? -10 : rand_range(st, 10, 20), col, 26);
        } else {
            int16_t x = rand_range(st, 40, 200);
            int16_t y = rand_range(st, 48, 168);
            ivy_particle_kind_t k = (i % 2 == 0) ? IVY_PARTICLE_HEART : IVY_PARTICLE_STAR;
            uint16_t col = (k == IVY_PARTICLE_HEART) ? COL565_PINK : COL565_GOLD;
            spawn_particle(st, k, x, y, rand_range(st, -12, 12), rand_range(st, -16, -4), col, 26);
        }
    }
}

void ivy_card_logic_init(ivy_card_state_t *st) {
    if (!st) return;
    memset(st, 0, sizeof(*st));
    st->hero_mode = IVY_MODE_STORY;
    st->story_phase = IVY_STORY_WORKING;
    st->turn_view = IVY_TURN_FRONT;
    st->expr_kind = IVY_EXPR_LAUGH;
    st->card_tab = IVY_TAB_PROFILE;
    st->poster_mode = false;
    st->offwork_cheered = false;
    st->rng_state = 0x517CC1B7u;
}

void ivy_card_logic_on_button(ivy_card_state_t *st, ivy_btn_t btn, ivy_btn_ev_t ev) {
    if (!st) return;

    if (btn == IVY_BTN_UP && ev == IVY_EV_CLICK) {
        st->hero_mode = (ivy_hero_mode_t)(((int)st->hero_mode + 1) % IVY_MODE_COUNT);
        st->bounce_ticks = 10;
        burst_celebration(st, 6);
        return;
    }

    if (btn == IVY_BTN_DOWN && ev == IVY_EV_CLICK) {
        st->card_tab = (ivy_card_tab_t)(((int)st->card_tab + 1) % IVY_TAB_COUNT);
        return;
    }

    if (btn == IVY_BTN_OK && ev == IVY_EV_LONG) {
        st->poster_mode = !st->poster_mode;
        return;
    }

    if (btn == IVY_BTN_OK && (ev == IVY_EV_CLICK || ev == IVY_EV_DOUBLE)) {
        if (st->hero_mode == IVY_MODE_STORY) {
            if (st->story_phase == IVY_STORY_WORKING) {
                st->story_phase = IVY_STORY_CLOCK_OUT_SEQ;
                st->story_tick = 0;
                st->offwork_cheered = false;
                st->banner_burst_done = false;
                st->bounce_ticks = 8;
            } else if (st->story_phase == IVY_STORY_CLOCK_OUT_SEQ) {
                burst_celebration(st, 6);
            } else {
                if (ev == IVY_EV_DOUBLE || st->offwork_cheered) {
                    st->story_phase = IVY_STORY_WORKING;
                    st->story_tick = 0;
                    st->offwork_cheered = false;
                    st->banner_burst_done = false;
                    st->bounce_ticks = 8;
                } else {
                    st->offwork_cheered = true;
                    st->jump_ticks = 14;
                    burst_celebration(st, 16);
                }
            }
        } else if (st->hero_mode == IVY_MODE_TURNAROUND) {
            st->turn_view = (ivy_turn_view_t)(((int)st->turn_view + 1) % IVY_TURN_COUNT);
            st->bounce_ticks = 10;
            burst_celebration(st, 8);
        } else {
            st->expr_kind = (ivy_expr_kind_t)(((int)st->expr_kind + 1) % IVY_EXPR_COUNT);
            st->bounce_ticks = 12;
            burst_expression(st, st->expr_kind);
        }
    }
}

void ivy_card_logic_tick(ivy_card_state_t *st) {
    if (!st) return;
    st->tick++;

    if (st->bounce_ticks > 0) {
        st->bounce_ticks--;
    }
    if (st->jump_ticks > 0) {
        st->jump_ticks--;
    }

    /* Update active particles */
    for (int i = 0; i < IVY_PARTICLE_MAX; ++i) {
        ivy_particle_t *p = &st->particles[i];
        if (p->kind == IVY_PARTICLE_NONE || p->ttl == 0) {
            p->kind = IVY_PARTICLE_NONE;
            continue;
        }
        p->x_q4 = (int16_t)(p->x_q4 + p->vx_q4);
        p->y_q4 = (int16_t)(p->y_q4 + p->vy_q4);
        if (p->kind == IVY_PARTICLE_CONFETTI || p->kind == IVY_PARTICLE_SWEAT) {
            p->vy_q4 = (int16_t)(p->vy_q4 + 1);
        }
        p->ttl--;
        if (p->ttl == 0) {
            p->kind = IVY_PARTICLE_NONE;
        }
    }

    if (st->hero_mode == IVY_MODE_STORY) {
        st->story_tick++;
        if (st->story_phase == IVY_STORY_WORKING) {
            if ((st->tick % 9u) == 0u) {
                int16_t side = (next_rand(st) & 1u) ? 1 : -1;
                int16_t x = (int16_t)(120 + side * rand_range(st, 40, 74));
                int16_t y = rand_range(st, 34, 72);
                spawn_particle(st, IVY_PARTICLE_SWEAT, x, y,
                               (int16_t)(side * 2), 12, COL565_CYAN, 22);
            }
        } else if (st->story_phase == IVY_STORY_CLOCK_OUT_SEQ) {
            if (st->story_tick == SEQ_PHASE2_END && !st->banner_burst_done) {
                st->banner_burst_done = true;
                burst_celebration(st, 18);
            }
            if (st->story_tick >= SEQ_TOTAL_TICKS) {
                st->story_phase = IVY_STORY_OFFWORK_LOOP;
                st->story_tick = 0;
            }
        } else {
            if ((st->tick % 10u) == 0u) {
                int16_t x = rand_range(st, 28, 212);
                int16_t y = rand_range(st, 110, 200);
                ivy_particle_kind_t k = (next_rand(st) % 2u == 0u) ? IVY_PARTICLE_HEART : IVY_PARTICLE_STAR;
                uint16_t col = (k == IVY_PARTICLE_HEART) ? COL565_PINK
                             : ((next_rand(st) & 1u) ? COL565_GOLD : COL565_LIME);
                spawn_particle(st, k, x, y, rand_range(st, -4, 4), rand_range(st, -14, -7), col, 24);
            }
        }
    } else if (st->hero_mode == IVY_MODE_TURNAROUND) {
        if ((st->tick % 12u) == 0u) {
            int16_t side = (next_rand(st) & 1u) ? 1 : -1;
            int16_t x = (int16_t)(120 + side * rand_range(st, 48, 86));
            int16_t y = rand_range(st, 48, 188);
            ivy_particle_kind_t k = (next_rand(st) % 2u == 0u) ? IVY_PARTICLE_HEART : IVY_PARTICLE_STAR;
            uint16_t col = (k == IVY_PARTICLE_HEART) ? COL565_PINK
                         : ((next_rand(st) & 1u) ? COL565_GOLD : COL565_LIME);
            spawn_particle(st, k, x, y, 0, -9, col, 24);
        }
    } else {
        if ((st->tick % 11u) == 0u) {
            if (st->expr_kind == IVY_EXPR_LAUGH) {
                spawn_particle(st, IVY_PARTICLE_HEART, rand_range(st, 36, 204), 178,
                               rand_range(st, -4, 4), -12, COL565_PINK, 26);
            } else if (st->expr_kind == IVY_EXPR_DEADPAN) {
                bool heart = (next_rand(st) % 3u) == 0u;
                spawn_particle(st, heart ? IVY_PARTICLE_HEART : IVY_PARTICLE_SWEAT,
                               rand_range(st, 42, 198), heart ? 150 : 38,
                               0, heart ? -10 : 12, heart ? COL565_PINK : COL565_CYAN, 22);
            } else {
                ivy_particle_kind_t k = (next_rand(st) % 2u == 0u) ? IVY_PARTICLE_HEART : IVY_PARTICLE_STAR;
                uint16_t col = (k == IVY_PARTICLE_HEART) ? COL565_PINK
                             : ((st->expr_kind == IVY_EXPR_SHOCK) ? COL565_LIME : COL565_GOLD);
                spawn_particle(st, k, rand_range(st, 34, 206),
                               rand_range(st, 48, 190), 0, -9, col, 24);
            }
        }
    }
}

static int16_t bounce_offset(uint16_t rem_ticks) {
    if (rem_ticks == 0) return 0;
    /* Quick up-down pop */
    if (rem_ticks > 8) return -5;
    if (rem_ticks > 5) return -7;
    if (rem_ticks > 2) return -3;
    return -1;
}

void ivy_card_logic_get_snapshot(const ivy_card_state_t *st, ivy_render_snapshot_t *out) {
    if (!st || !out) return;
    memset(out, 0, sizeof(*out));

    int16_t base_bounce = bounce_offset(st->bounce_ticks);
    int16_t jump_dy = 0;
    if (st->jump_ticks > 0) {
        /* Smooth parabolic hop up to -14px */
        int32_t t = 14 - (int32_t)st->jump_ticks;
        jump_dy = (int16_t)(-(t * (14 - t)) / 4);
    }

    if (st->hero_mode == IVY_MODE_STORY) {
        if (st->story_phase == IVY_STORY_WORKING) {
            static const int8_t type_dx[4] = { -1, 0, 1, 0 };
            out->main_sprite = IVY_SPRITE_WORK_0;
            out->show_offwork_banner = false;
            out->sprite_dx = type_dx[(st->tick >> 1) & 3u];
            out->sprite_dy = (int16_t)(((st->tick & 3u) == 0u ? 1 : 0) + base_bounce);
            out->mood_pct = 25;
            out->stage_badge_utf8 = "♥ 宝宝搬砖中";
            out->mode_pill = "求抱抱 T^T";
            out->stage_hint_ascii = "按OK接宝贝下班 ♥";
        } else if (st->story_phase == IVY_STORY_CLOCK_OUT_SEQ) {
            if (st->story_tick < SEQ_PHASE1_END) {
                out->main_sprite = IVY_SPRITE_WORK_1;
                out->show_offwork_banner = false;
                out->sprite_dx = 0;
                out->sprite_dy = (st->story_tick < 4u) ? -4 : base_bounce;
                out->mood_pct = 55;
                out->stage_badge_utf8 = "✦ 到点下班啦";
                out->mode_pill = "哇! ^o^";
                out->stage_hint_ascii = "准备关电脑咯 ♪";
            } else if (st->story_tick < SEQ_PHASE2_END) {
                out->main_sprite = IVY_SPRITE_WORK_2;
                out->show_offwork_banner = false;
                out->sprite_dx = 0;
                out->sprite_dy = ((st->story_tick - SEQ_PHASE1_END) < 5u) ? -2 : 0;
                out->mood_pct = 80;
                out->stage_badge_utf8 = "♥ 收拾小书包";
                out->mode_pill = "超开心 ^v^";
                out->stage_hint_ascii = "拒绝加班! 快溜 ♥";
            } else {
                out->main_sprite = IVY_SPRITE_WORK_3;
                out->show_offwork_banner = true;
                out->sprite_dx = 0;
                out->sprite_dy = (int16_t)(((st->story_tick & 4u) ? -3 : 0) + base_bounce);
                out->banner_dy = (int16_t)((st->story_tick & 8u) ? -2 : 0);
                out->mood_pct = 100;
                out->stage_badge_utf8 = "★ 满血复活啦";
                out->mode_pill = "好耶! ^o^";
                out->stage_hint_ascii = "自由啦 ♥";
            }
        } else {
            /* 84-tick cheerful off-work loop: stand -> wave -> run -> run -> wave */
            uint32_t phase = st->story_tick % 84u;
            int16_t run_dx = 0;
            int16_t bob_dy = 0;
            if (phase < 16u) {
                out->main_sprite = IVY_SPRITE_WORK_4;
                bob_dy = (phase & 8u) ? -1 : 0;
            } else if (phase < 36u) {
                out->main_sprite = IVY_SPRITE_WORK_5;
                bob_dy = ((phase - 16u) & 4u) ? -2 : 0;
            } else if (phase < 68u) {
                uint32_t run_t = phase - 36u;
                out->main_sprite = ((run_t / 6u) & 1u) ? IVY_SPRITE_WORK_7 : IVY_SPRITE_WORK_6;
                /* Smooth back-and-forth trot -12..+12 px */
                int32_t half = (int32_t)(run_t <= 16u ? run_t : (32u - run_t));
                run_dx = (int16_t)((half * 24) / 16 - 12);
                bob_dy = (run_t & 4u) ? -4 : 0;
            } else {
                out->main_sprite = IVY_SPRITE_WORK_5;
                bob_dy = ((phase - 68u) & 4u) ? -2 : 0;
            }
            out->show_offwork_banner = true;
            out->sprite_dx = run_dx;
            out->sprite_dy = (int16_t)(bob_dy + base_bounce + jump_dy);
            out->banner_dy = (int16_t)((st->tick & 8u) ? -2 : 0);
            out->mood_pct = 100;
            out->stage_badge_utf8 = "♥ 快乐小神仙";
            out->mode_pill = st->offwork_cheered ? "再玩一次 ♥" : "去约会咯 ♪";
            out->stage_hint_ascii = st->offwork_cheered ? "按OK重新打卡 ♥" : "按OK欢呼庆祝 ♥";
        }
    } else if (st->hero_mode == IVY_MODE_TURNAROUND) {
        static const ivy_sprite_id_t turn_ids[IVY_TURN_COUNT] = {
            IVY_SPRITE_TURN_FRONT, IVY_SPRITE_TURN_SIDE, IVY_SPRITE_TURN_BACK,
        };
        static const char *turn_badges[IVY_TURN_COUNT] = {
            "♥ 正面也超甜", "✦ 侧颜小仙女", "★ 背影也迷人",
        };
        static const char *turn_pills[IVY_TURN_COUNT] = {
            "甜酷宝贝 ★", "酷飒满分 ♥", "双色头发 ♥",
        };
        out->main_sprite = turn_ids[st->turn_view];
        out->show_offwork_banner = false;
        out->sprite_dx = 0;
        out->sprite_dy = (int16_t)(((st->tick % 24u) < 12u ? 0 : -1) + base_bounce);
        out->mood_pct = 100;
        out->stage_badge_utf8 = turn_badges[st->turn_view];
        out->mode_pill = turn_pills[st->turn_view];
        out->stage_hint_ascii = "按OK转圈圈看穿搭 ✦";
    } else {
        static const ivy_sprite_id_t expr_ids[IVY_EXPR_COUNT] = {
            IVY_SPRITE_EXPR_LAUGH, IVY_SPRITE_EXPR_SHOCK,
            IVY_SPRITE_EXPR_DEADPAN, IVY_SPRITE_EXPR_SMIRK,
        };
        static const char *expr_badges[IVY_EXPR_COUNT] = {
            "♥ 笑眼弯弯", "✦ 呆萌小表情", "♪ 摸鱼充电中", "★ 傲娇小女王",
        };
        static const char *expr_pills[IVY_EXPR_COUNT] = {
            "甜度满分 ♥", "小礼物?! :O", "要抱抱 -_-", "甜酷拿捏 ;)",
        };
        static const char *expr_hints[IVY_EXPR_COUNT] = {
            "宝贝笑起来最好看 ♥",
            "叮! 收到专属小礼物 ♥",
            "累了就歇会儿 抱抱你 ♥",
            "全世界最酷的小宝贝 ★",
        };
        static const uint8_t expr_moods[IVY_EXPR_COUNT] = { 100, 82, 58, 99 };
        out->main_sprite = expr_ids[st->expr_kind];
        out->show_offwork_banner = false;
        out->sprite_dx = (st->expr_kind == IVY_EXPR_SHOCK && st->bounce_ticks > 6u)
                       ? (int16_t)((st->tick & 1u) ? 2 : -2) : 0;
        out->sprite_dy = (int16_t)(((st->tick % 20u) < 10u ? 0 : -1) + base_bounce);
        out->mood_pct = expr_moods[st->expr_kind];
        out->stage_badge_utf8 = expr_badges[st->expr_kind];
        out->mode_pill = expr_pills[st->expr_kind];
        out->stage_hint_ascii = expr_hints[st->expr_kind];
    }
}
